    private void simpan() {
        String npm = npmField.getText().trim();
        String nama = namaField.getText().trim();

        if (adaSalah(Validator.npm(npm), npmField)) {
            return;
        }
        if (model.adaNpm(npm)) {
            adaSalah("NPM " + npm + " sudah terdaftar", npmField);
            return;
        }
        // Berhenti di kesalahan pertama: isian lain tidak terhapus
        if (adaSalah(Validator.nama(nama), namaField)
                || adaSalah(Validator.nilai(tugasField.getText(), "Tugas"), tugasField)
                || adaSalah(Validator.nilai(utsField.getText(), "UTS"), utsField)
                || adaSalah(Validator.nilai(uasField.getText(), "UAS"), uasField)) {
            return;
        }
        model.tambah(new NilaiMahasiswa(npm, nama,
                Integer.parseInt(tugasField.getText().trim()),
                Integer.parseInt(utsField.getText().trim()),
                Integer.parseInt(uasField.getText().trim())));
        bersihkan();
        perbaruiRingkasan();
    }

    /**
     * Menampilkan pesan dan memindahkan kursor. Mengembalikan true jika ada
     * kesalahan.
     */
    private boolean adaSalah(String pesan, JComponent isian) {
        if (pesan == null) {
            return false;
        }
        pesanLabel.setText(pesan);
        isian.requestFocusInWindow();
        return true;
    }

    private void bersihkan() {
        npmField.setText("");
        namaField.setText("");
        tugasField.setText("");
        utsField.setText("");
        uasField.setText("");
        pesanLabel.setText(" ");
        npmField.requestFocusInWindow();
    }

    private void perbaruiRingkasan() {
        ringkasanLabel.setText("Jumlah mahasiswa: " + model.getRowCount()
                + ", rata-rata nilai akhir: "
                + NilaiMahasiswa.formatNilai(model.rataRataAkhir()));
    }

